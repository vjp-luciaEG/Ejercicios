DELIMITER //
DROP FUNCTION IF EXISTS MOSTRAR_RESERVAS
//
CREATE FUNCTION MOSTRAR_RESERVAS(ID_CLI INT) RETURNS INT
DETERMINISTIC
BEGIN
	DECLARE NUM_RESERVAS INT;
    SELECT count(R.ID) 
    FROM RESERVAS R 
    WHERE ID_CLIENTE = ID_CLI
    INTO NUM_RESERVAS ;
    
    RETURN NUM_RESERVAS;
END
//
DELIMITER ;
