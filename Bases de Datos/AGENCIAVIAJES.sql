CREATE FUNCTION MOSTRAR_RESERVAS_CLI(ID_CLI INT) RETURNS VARCHAR(100)
DETERMINISTIC
BEGIN
	DECLARE NUM_RESERVAS INT;
    DECLARE MENSAJE VARCHAR(100);
    
    SELECT count(R.ID) 
    INTO NUM_RESERVAS 
    FROM RESERVAS R 
    WHERE R.ID_CLIENTE = ID_CLI AND R.FECHA_SALIDA IS NOT NULL;
    
   IF NUM_RESERVAS > 0 THEN
        SET MENSAJE = CONCAT_WS(' ','El cliente', ID_CLI, 'tiene',NUM_RESERVAS, 'reservas activas');
    ELSE
        SET MENSAJE = CONCAT_WS(' ','El cliente', ID_CLI, 'no tiene reservas activas');
    END IF;

    RETURN MENSAJE;
END//
DELIMITER ;
