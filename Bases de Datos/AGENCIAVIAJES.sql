//
CREATE TRIGGER REGISTRAR_LOG
BEFORE UPDATE ON ALOJAMIENTOS
FOR EACH ROW
BEGIN
	IF OLD.PRECIO_NOCHE != NEW.PRECIO_NOCHE THEN
	INSERT INTO LOG_CAMBIOS_PRECIO(ID_ALOJAMIENTO,PRECIO_ANTERIOR,PRECIO_NUEVO,FECHA_CAMBIO) 
    VALUES (OLD.ID,OLD.PRECIO_NOCHE,NEW.PRECIO_NOCHE,current_date());
	END IF;
END //
