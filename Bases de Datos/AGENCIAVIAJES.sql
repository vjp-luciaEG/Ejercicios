-- EJERCICIO 1
-- Crear un procedimiento que liste todas las reservas junto con el nombre del cliente y del alojamiento. 
DELIMITER //
//
CREATE PROCEDURE MOSTRAR_RESERVAS()
BEGIN
	SELECT R.*,C.NOMBRE,A.NOMBRE
    FROM RESERVAS R
    INNER JOIN CLIENTES C ON C.ID = R.ID_CLIENTE
    INNER JOIN ALOJAMIENTOS A
    ON R.ID_ALOJAMIENTO = A.ID;
END//
DELIMITER ;
CALL MOSTRAR_RESERVAS();

