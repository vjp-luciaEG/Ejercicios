-- Crear un trigger que impida insertar una reserva duplicada del mismo cliente, alojamiento y fechas. 
DELIMITER //
DROP TRIGGER IF EXISTS T_RESERVA
//
CREATE TRIGGER T_RESERVA
BEFORE INSERT ON RESERVAS
FOR EACH ROW
BEGIN
	DECLARE CONTADOR INT;
    
    SELECT COUNT(*) FROM RESERVAS
    WHERE ID_CLIENTE = NEW.ID_CLIENTE
    AND ID_ALOJAMIENTO = NEW.ID_ALOJAMIENTO
    AND FECHA_ENTRADA = NEW.FECHA_ENTRADA
    AND FECHA_SALIDA = NEW.FECHA_SALIDA
    INTO CONTADOR;
    
	IF CONTADOR > 0 THEN
		SIGNAL SQLSTATE'45000'
        SET MESSAGE_TEXT = 'RESERVA DUPLICADA';
	END IF;
END //
DELIMITER ;

