-- Crear una función que calcule el  total de ingresos generados (suma de noches * precio).por un alojamiento cuyo id le pasamos como parámetro 
DELIMITER //
DROP FUNCTION IF EXISTS CALCULAR_INGRESOS
//
CREATE FUNCTION CALCULAR_INGRESOS(ID_ALO INT) RETURNS DECIMAL(6,2)
DETERMINISTIC
BEGIN
	DECLARE INGRESOS DECIMAL(6,2);
    SELECT IFNULL(SUM(DATEDIFF(R.FECHA_SALIDA,R.FECHA_ENTRADA) * A.PRECIO_NOCHE),0) 
    
    FROM ALOJAMIENTOS A INNER JOIN RESERVAS R 
    ON R.ID_ALOJAMIENTO = A.ID
    WHERE A.ID = ID_ALO
    INTO INGRESOS;
    
    RETURN INGRESOS;
END
//
DELIMITER ;
SELECT CALCULAR_INGRESOS(1);

-- Crear una función que devuelva una cadena de texto con el nombre del cliente y número de reservas que ha hecho.
DELIMITER //
DROP FUNCTION IF EXISTS MOSTRAR_RESERVAS_CLI
//
CREATE FUNCTION MOSTRAR_RESERVAS_CLI(ID_CLI INT) RETURNS VARCHAR(100)
DETERMINISTIC
BEGIN
	DECLARE NOM_CLI VARCHAR(100);
	DECLARE NUM_RESERVAS INT;
    
    SELECT NOMBRE
    FROM CLIENTES
    WHERE ID = ID_CLI
    INTO NOM_CLI;
    
    SELECT count(R.ID) 
    FROM RESERVAS R 
    WHERE ID_CLIENTE = ID_CLI
    INTO NUM_RESERVAS;
    
    RETURN CONCAT_WS(' ', NOM_CLI,'ha realizado',NUM_RESERVAS,'reservas');
END//
DELIMITER ;
