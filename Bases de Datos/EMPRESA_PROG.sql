CREATE FUNCTION CALCULAR_SUELDOS(NUM_DPTO INT) RETURNS DECIMAL(9,2) 
DETERMINISTIC 
BEGIN 
	DECLARE RESULTADO DECIMAL(9,2); 
    SELECT sum(SALARIO)
    FROM EMP
    WHERE N_DPTO = NUM_DPTO
    GROUP BY N_DPTO
    INTO RESULTADO;
RETURN RESULTADO; 
END; 
