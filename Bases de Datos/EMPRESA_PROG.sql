CREATE PROCEDURE MOSTRAR_DATOS_EMP()
BEGIN
	SELECT APELLIDO, SALARIO, OFICIO, ifnull(D.NOM_DPTO, 'NO TIENE DEPARTAMENTO') AS NOM_DPTO
    FROM EMP E LEFT JOIN DPTO D
    ON E.N_DPTO = D.DPTO;
END//
DELIMITER ;
CALL MOSTRAR_DATOS_EMP();

