CREATE FUNCTION CALCULAR_DEPARTAMENTOS() RETURNS INT
DETERMINISTIC
BEGIN
	DECLARE RESULTADO INT;
    SELECT COUNT(*)
    FROM DPTO INTO RESULTADO;
    RETURN RESULTADO;
END//
DELIMITER ;
