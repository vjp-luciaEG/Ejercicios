DELIMITER //
DROP FUNCTION IF EXISTS MENSAJE
//
CREATE FUNCTION MENSAJE(DPTO INT) RETURNS VARCHAR(100)
DETERMINISTIC
BEGIN
	DECLARE MENSAJE VARCHAR(100);
    DECLARE CONTADOR INT;
    
    SELECT COUNT(*)
    FROM EMP 
    WHERE N_DPTO=DPTO
    GROUP BY N_DPTO
    INTO CONTADOR;
    
    IF CONTADOR>=3 THEN
		SELECT concat_ws(' ','3 O MAS EMPLEADOS EN EL DPTO',DPTO) INTO MENSAJE;
    ELSE
		SELECT concat_ws(' ','MENOS DE 3 EMPLEADOS EN EL DPTO',DPTO) INTO MENSAJE;
    END IF;
    
    RETURN MENSAJE;
END//
DELIMITER ;
SELECT MENSAJE(40);


DELIMITER //
DROP FUNCTION IF EXISTS F4
//
CREATE FUNCTION F4(NOMBRE VARCHAR(50)) RETURNS DECIMAL(9,2)
DETERMINISTIC
BEGIN
    DECLARE RESULTADO DECIMAL(9,2);
    
    SELECT MAX(SALARIO)
    FROM EMP INNER JOIN DPTO 
    ON N_DPTO = DPTO
    WHERE NOM_DPTO=NOMBRE
    INTO RESULTADO;
    
    RETURN RESULTADO;
END//
DELIMITER ;
