DELIMITER //
//
CREATE PROCEDURE MOSTRAR_DPTO(NUM_DPTO INT)
BEGIN
	SELECT D.*, count(E.N_DPTO) AS NUMERO_EMPLEADOS
    FROM DPTO D INNER JOIN EMP E
    ON D.DPTO = E.N_DPTO
    WHERE D.DPTO = NUM_DPTO
    GROUP BY D.NOM_DPTO, E.N_DPTO;
END//
DELIMITER ;
CALL MOSTRAR_DPTO(30);


