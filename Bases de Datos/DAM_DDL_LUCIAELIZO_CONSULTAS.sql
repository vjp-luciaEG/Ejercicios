CREATE TABLE SERIEPLATAFORMA (
COD_SERIE INT,
COD_PLATAFORMA INT,
FECHA_INCLUSION DATE NOT NULL,
CONSTRAINT SERIEPLATAFORMA_PK PRIMARY KEY (COD_SERIE,COD_PLATAFORMA)
);
ALTER TABLE SERIEPLATAFORMA
ADD CONSTRAINT SERIEPLATAFORMA_SERIES_FK
	FOREIGN KEY (COD_SERIE)
    REFERENCES SERIES(COD_SERIE)
    ON DELETE CASCADE ON UPDATE CASCADE,
ADD CONSTRAINT SERIEPLATAFORMA_PLATAFORMAS_FK
	FOREIGN KEY (COD_PLATAFORMA)
    REFERENCES PLATAFORMAS(COD_PLATAFORMA)
    ON DELETE CASCADE ON UPDATE CASCADE;
    
ALTER TABLE SERIEPLATAFORMA
MODIFY COD_SERIE INT UNSIGNED;

ALTER TABLE SERIEPLATAFORMA
ADD CONSTRAINT FECHA_INCLUSION_CK CHECK (year(FECHA_INCLUSION) BETWEEN 2000 AND 2025); 

