-- 5.1
SELECT S.NOMBRE_SERIE, P.NOMBRE_ACTOR
FROM SERIES S INNER JOIN SERIEACTOR SA
ON S.COD_SERIE = SA.COD_SERIE
INNER JOIN PERSONAJES P
ON SA.COD_ACTOR = P.COD_ACTOR;

-- 5.2
SELECT S.NOMBRE_SERIE
FROM SERIES S INNER JOIN TEMPORADA T
ON S.COD_SERIE = T.COD_SERIE
GROUP BY T.COD_SERIE
HAVING count(NUM_TEMPORADA) > 1;

-- 5.3
SELECT S.NOMBRE_SERIE
FROM SERIES S INNER JOIN SERIEPLATAFORMA SP
ON S.COD_SERIE = SP.COD_SERIE
INNER JOIN PLATAFORMAS P
ON SP.COD_PLATAFORMA = P.COD_PLATAFORMA
GROUP BY S.NOMBRE_SERIE
HAVING COUNT(P.COD_PLATAFORMA) > 1;

-- 5.4
SELECT P.NOMBRE_ACTOR
FROM SERIES S INNER JOIN SERIEACTOR SA
ON S.COD_SERIE = SA.COD_SERIE
INNER JOIN PERSONAJES P
ON SA.COD_ACTOR = P.COD_ACTOR
WHERE S.GENERO = 'FANTASIA';

-- 5.5
SELECT S.NOMBRE_SERIE
FROM SERIES S
WHERE S.AÑO_ESTRENO > (SELECT AVG(AÑO_ESTRENO) FROM SERIES);

-- 5.6
SELECT DISTINCT S.NOMBRE_SERIE
FROM SERIES S
INNER JOIN TEMPORADA T
ON S.COD_SERIE = T.COD_SERIE
WHERE YEAR(T.FECHA_ESTRENO) > 2021;

-- 5.7
SELECT P.NOMBRE_ACTOR
FROM PERSONAJES P INNER JOIN SERIEACTOR SA
ON P.COD_ACTOR = SA.COD_ACTOR
INNER JOIN SERIES S 
ON SA.COD_SERIE= S.COD_SERIE
INNER JOIN SERIEPLATAFORMA SP
ON S.COD_SERIE = SP.COD_SERIE
INNER JOIN PLATAFORMAS PL
ON SP.COD_PLATAFORMA = PL.COD_PLATAFORMA
WHERE NOMBRE_PLATAFORMA = 'NETFLIX';

-- 5.8
SELECT S.NOMBRE_SERIE
FROM SERIES S INNER JOIN TEMPORADA T
ON S.COD_SERIE = T.COD_SERIE
WHERE T.COD_SERIE IS NULL;

-- 5.9
SELECT S.NOMBRE_SERIE
FROM SERIES S INNER JOIN TEMPORADA T
ON S.COD_SERIE = T.COD_SERIE
WHERE T.FECHA_ESTRENO = (SELECT MAX(FECHA_ESTRENO) FROM TEMPORADA);

-- 5.10
SELECT P.NOMBRE_ACTOR
FROM PERSONAJES P INNER JOIN SERIEACTOR SA
ON P.COD_ACTOR = SA.COD_ACTOR
INNER JOIN SERIES S 
ON SA.COD_SERIE= S.COD_SERIE
INNER JOIN SERIEPLATAFORMA SP
ON S.COD_SERIE = SP.COD_SERIE
INNER JOIN PLATAFORMAS PL
ON SP.COD_PLATAFORMA = PL.COD_PLATAFORMA
GROUP BY  P.COD_ACTOR
HAVING COUNT(DISTINCT PL.COD_PLATAFORMA) > 1;